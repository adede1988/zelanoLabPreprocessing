# fr_scratch.ps1 - the SCRATCH universe of the full-EEG-rerun driver (dot-source after fr_lib.ps1 / fr_final.ps1).
#
# A scratch universe is a copy of exactly what one manifest row needs, on E:, so that the whole state machine (backup + SHA-256,
# move to superseded_261022, makeOutDat + main with ZLP_CARRY_FROM, fr_verify.m, restore) can be run without touching R: (read
# only), the master sheet or the sheet lock:
#   <ScratchRoot>\lc\...      the session folder (raw, behavior; not AtlasData / preProc) and the behavior folders of the task,
#                             copied from R:, plus the current final; and Admin\Data\dataTracking.xlsx = the STAGING sheet
#   <ScratchRoot>\cfg\labPaths_local.m   points labCommon at lc ; everything labPaths derives from labCommon follows (session
#                             roots, figure folder, behavior folders, the sheet); code, EEGLAB and the Google-Drive target
#                             traces stay the real, read-only ones
#   <ScratchRoot>\state, backup, compare, logs   as the real ones
# processedBehavior\<id>_*.csv goes to the repo's processedBehavior folder (git-ignored), exactly as in a real run.

$script:FrLabBases = @{ codePre = 'E:\GitHub\'; eeglab = 'C:\Users\dtf8829\Documents\eeglab2025.0.0'; gdrive = 'G:\My Drive\'; fieldtrip = 'E:\fieldtrip-20260518' }

# never mirrored (a session folder also holds videos, the Neuralynx / BrainVision exports and the other pipeline outputs: tens of GB)
$script:FrMirrorSkipDirs = @('AtlasData', 'preProc', 'brainProductsDat', 'BehavioralVideo', '*Video*', '*video*', 'superseded_*')
$script:FrMirrorSkipFiles = @('*.avi', '*.mp4', '*.mov', '*.mkv', '*.wmv', '*.mpg', '*.ncs', '*.nev', '*.nse', '*.ntt', '*.nrd', '*.eeg', '*.zip')
$script:FrMirrorMaxGB = 20       # a mirror larger than this is refused (a surprise folder must not fill E:)

function Copy-FrTree {
    # robocopy src -> dst (read-only on src); exit codes 0-7 are success.  A dry run first: the bytes that WOULD be copied must
    # stay under MaxGB, else nothing is copied.
    param([string]$Src, [string]$Dst, [string[]]$ExcludeDirs = @(), [double]$MaxGB = 0)
    $common = @('/E', '/R:2', '/W:5', '/NP', '/NFL', '/NDL', '/XF') + $script:FrMirrorSkipFiles + @('/XD') + $script:FrMirrorSkipDirs + $ExcludeDirs
    if ($MaxGB -gt 0) {
        $o = & robocopy.exe $Src $Dst @common '/L' '/NJH' '/BYTES' 2>&1 | Out-String
        $m = [regex]::Match($o, '(?m)^\s*Bytes\s*:\s*(\d+)\s+(\d+)')
        if (-not $m.Success) { throw "robocopy dry run gave no size for $Src" }
        $gb = [double]$m.Groups[2].Value / 1GB
        if ($gb -gt $MaxGB) { throw ("the mirror of {0} would copy {1:N1} GB (limit {2} GB): refused" -f $Src, $gb, $MaxGB) }
        Write-FrLog 'INFO' ("  mirror of {0}: {1:N2} GB" -f (Split-Path -Leaf $Src), $gb)
    }
    New-Item -ItemType Directory -Force -Path $Dst | Out-Null
    & robocopy.exe $Src $Dst @common '/NJH' '/NJS' | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE) for $Src" }
}

function Initialize-FrScratchRow {
    # makes the scratch universe $U ready for one manifest row (idempotent: the mirror is made once per session)
    param($Row, $U, [switch]$NoMirror, [switch]$Reset)
    $FR = $script:FR
    $lc = $U.LabCommon.TrimEnd('\')
    # --- cfg: labPaths_local.m
    $B = $script:FrLabBases
    $m = @(
        'function L = labPaths_local()',
        '% generated by fr_scratch.ps1: the scratch universe (labCommon on E:); code / EEGLAB / Google Drive stay the real ones',
        ("L.codePre   = '{0}';" -f $B.codePre),
        ("L.eeglab    = '{0}';" -f $B.eeglab),
        ("L.labCommon = '{0}\';" -f $lc),
        ("L.gdrive    = '{0}';" -f $B.gdrive),
        ("L.fieldtrip = '{0}';" -f $B.fieldtrip),
        'end')
    [IO.File]::WriteAllText((Join-Path $U.CfgDir 'labPaths_local.m'), ($m -join "`r`n") + "`r`n")
    # --- staging sheet (a copy of the master; the pipeline writes this one)
    $sheetDst = Join-Path $lc 'Admin\Data\dataTracking.xlsx'
    if (-not (Test-Path -LiteralPath $sheetDst)) {
        New-Item -ItemType Directory -Force -Path (Split-Path $sheetDst) | Out-Null
        Copy-Item -LiteralPath $FR.RProbe -Destination $sheetDst -Force
        Write-FrLog 'INFO' 'staging sheet copied from the master'
    }
    # --- mirror of the session
    $canon = $FR.CanonLC
    $live = $Row.finalPath
    $sessDir = Split-Path -Parent (Split-Path -Parent $live)           # <root>\<id>
    $sessDst = Resolve-FrScratchPath $sessDir $U
    $stamp = Join-Path $sessDst ('.fr_mirrored_' + $Row.task)       # per task: the raw folders copied depend on the task
    if ($Reset) {
        # forget the scratch state of this key (the mirror stays)
        Remove-Item -LiteralPath (Join-Path $U.State ($Row.key + '.json')) -Force -ErrorAction SilentlyContinue
        Remove-Item -LiteralPath (Join-Path (Join-Path $U.Backup $Row.task) $Row.sessID) -Recurse -Force -ErrorAction SilentlyContinue
    }
    if (-not $NoMirror -and -not (Test-Path -LiteralPath $stamp)) {
        Write-FrLog 'INFO' "mirroring $sessDir -> $sessDst (raw / behavior; AtlasData and preProc are left out)"
        $t0 = Get-Date
        # only the raw folders of this task (a session folder holds the raw files of every task, up to ~20 GB); when no folder
        # matches the task's patterns (an unusual folder name) the whole raw folder is copied
        $inc = @{
            breathingTask = @('raw_breathing*'); cueTask = @('raw_cue*', 'raw_odorCue*'); cueTask3 = @('raw_cue*'); threshTask = @('raw_PEA*', 'raw_thresh*')
            O15 = @('raw_O15*'); EmotionalMovieTask = @('raw_*ovie*', 'raw_Emotional*'); alternating6Blocks = @('raw_alt*'); pacedBreathing = @('raw_paced*')
            respiratorySweep = @('raw_*weep*'); airPuff = @('raw_airPuff*'); detectNoOdor = @('raw_detect*', 'raw_odor*')
        }
        $xd = @()
        $pats = @($inc[$Row.task])
        if ($pats.Count -gt 0 -and $pats[0]) {
            $rawDirs = @(Get-ChildItem -LiteralPath (Join-Path $sessDir 'raw') -Directory -ErrorAction SilentlyContinue)
            $keep = @($rawDirs | Where-Object { $n = $_.Name; @($pats | Where-Object { $n -like $_ }).Count -gt 0 })
            if ($keep.Count -gt 0) { $xd += @($rawDirs | Where-Object { $keep.Name -notcontains $_.Name } | ForEach-Object { $_.FullName }) }
        }
        Copy-FrTree $sessDir $sessDst $xd $script:FrMirrorMaxGB
        # behavior folders that live outside the session folder
        $beh = @{
            cueTask = @('OBE_task_backup\tasks\olf_cuetask\results\olf_cuetask_results'); cueTask3 = @('OBE_task_backup\tasks\olf_cuetask\results\olf_cuetask_results')
            threshTask = @('OBE_task_backup\tasks\pea_threshold\results', 'OBE_task_backup\tasks\pea_threshold\results\results')
            detectNoOdor = @('OBE_task_backup\tasks\odor_detection\results\results_OBE_Odor_detection', 'OBE_task_backup\tasks\odor_detection\participants')
        }
        $sid = $Row.sessID
        foreach ($rel in @($beh[$Row.task])) {
            if (-not $rel) { continue }
            $src = Join-Path $canon $rel
            if (-not (Test-Path -LiteralPath $src)) { continue }
            Get-ChildItem -LiteralPath $src -Directory -Filter "$sid*" -ErrorAction SilentlyContinue | ForEach-Object {
                Copy-FrTree $_.FullName (Join-Path (Join-Path $lc $rel) $_.Name) @() 5
                Write-FrLog 'INFO' ("  behavior folder {0}" -f $_.Name)
            }
        }
        New-Item -ItemType Directory -Force -Path (Join-Path $sessDst 'preProc') | Out-Null
        Set-Content -LiteralPath $stamp -Value (Get-Date -Format s)
        Write-FrLog 'INFO' ("mirror done in {0} s" -f [int]((Get-Date) - $t0).TotalSeconds)
    }
    # --- the current final in the scratch preProc folder (only while the row has not been started there)
    $scratchLive = Resolve-FrScratchPath $live $U
    $st = Read-FrJson (Join-Path $U.State ($Row.key + '.json'))
    if (-not (Test-Path -LiteralPath $scratchLive) -and (-not $st -or $st.state -in @('pending', 'backedUp'))) {
        New-Item -ItemType Directory -Force -Path (Split-Path $scratchLive) | Out-Null
        Copy-Item -LiteralPath $live -Destination $scratchLive -Force
    }
}
